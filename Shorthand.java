public class Shorthand {
  public static void main(String[] args) {
    int num = 5 ; 
      num = num + 4; 
      System.out.println(num);
      num += 7;
      System.out.println(num);
      int num2 = 9 ;
      num2 -= 6;
      System.out.println(num2); 

      int num3 = 5 ; 
      num3 *= 4; 
      System.out.println(num3);

      int num4 = 6;
      num4 /= 2; 
      System.out.println(num4);

      int num5 = 7;
      num5 %= 3 ; 
      System.out.println(num5);
  }
}
